            await using (var insert = connection.CreateCommand())
            {
                insert.Transaction = transaction;
                insert.CommandText = @"
                    INSERT INTO password_reset_tokens (user_account_id, token_hash, expires_utc)
                    VALUES (@accountId, @tokenHash, @expiresUtc);";
