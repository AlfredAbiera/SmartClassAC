        catch (PostgresException exception) when (exception.SqlState == PostgresErrorCodes.UniqueViolation)
        {
            return false;
        }
    }

    public async Task<OperationResult> UpdateDefaultAdminCredentialsAsync(long accountId, string email, string? passwordHash, CancellationToken cancellationToken = default)
    {
        await using var connection = await OpenConnectionAsync(cancellationToken);
        await using var command = connection.CreateCommand();
        command.CommandText = passwordHash is null
            ? "UPDATE user_accounts SET email = @email WHERE id = @id AND is_default_admin = TRUE;"
            : "UPDATE user_accounts SET email = @email, password_hash = @passwordHash WHERE id = @id AND is_default_admin = TRUE;";
        command.Parameters.AddWithValue("@id", NpgsqlDbType.Bigint, accountId);
        command.Parameters.AddWithValue("@email", NpgsqlDbType.Varchar, email);
        if (passwordHash is not null) command.Parameters.AddWithValue("@passwordHash", NpgsqlDbType.Varchar, passwordHash);
        try
        {
            return await command.ExecuteNonQueryAsync(cancellationToken) == 1
                ? OperationResult.Success()
                : OperationResult.Failure("The default administrator account was not found.");
        }
        catch (PostgresException exception) when (exception.SqlState == PostgresErrorCodes.UniqueViolation)
        {
            return OperationResult.Failure("That email is already registered to another account.");
        }
    }

    public async Task<OperationResult> CreateTeacherAsync(CreateTeacherRequest request, string passwordHash, CancellationToken cancellationToken = default)
    {
        await using var connection = await OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        try
        {
            await using var account = connection.CreateCommand();
            account.Transaction = transaction;
            account.CommandText = @"
                INSERT INTO user_accounts (username, display_name, email, password_hash, role)
                VALUES (@username, @displayName, @email, @passwordHash, 'Teacher')
                RETURNING id;";
            account.Parameters.AddWithValue("@username", NpgsqlDbType.Varchar, request.Username);
            account.Parameters.AddWithValue("@displayName", NpgsqlDbType.Varchar, request.DisplayName);
            account.Parameters.AddWithValue("@email", NpgsqlDbType.Varchar, request.Email);
            account.Parameters.AddWithValue("@passwordHash", NpgsqlDbType.Varchar, passwordHash);
            var teacherId = (long)(await account.ExecuteScalarAsync(cancellationToken)
                ?? throw new InvalidOperationException("Supabase did not return the new teacher ID."));

            await using var templates = connection.CreateCommand();
            templates.Transaction = transaction;
            var values = new List<string>(FingerPositions.Length);
            templates.Parameters.AddWithValue("@teacherId", NpgsqlDbType.Bigint, teacherId);
            for (var index = 0; index < FingerPositions.Length; index++)
            {
                var finger = $"@finger{index}";
                var template = $"@template{index}";
                values.Add($"(@teacherId, {finger}, {template})");
                templates.Parameters.AddWithValue(finger, NpgsqlDbType.Varchar, FingerPositions[index]);
                templates.Parameters.AddWithValue(template, NpgsqlDbType.Uuid, Guid.NewGuid());
            }
            templates.CommandText = $"INSERT INTO fingerprint_templates (user_account_id, finger_position, template_identifier) VALUES {string.Join(", ", values)};";
            if (await templates.ExecuteNonQueryAsync(cancellationToken) != FingerPositions.Length)
            {
                throw new InvalidOperationException("All fingerprint templates could not be saved for the teacher account.");
            }

            await transaction.CommitAsync(cancellationToken);
            return OperationResult.Success();
        }
        catch (PostgresException exception) when (exception.SqlState == PostgresErrorCodes.UniqueViolation)
        {
            await transaction.RollbackAsync(cancellationToken);
            return OperationResult.Failure("That username or email is already registered.");
        }
        catch
        {
            await transaction.RollbackAsync(cancellationToken);
            throw;
        }
    }

    public async Task<IReadOnlyList<TeacherDirectoryEntry>> GetTeachersAsync(CancellationToken cancellationToken = default)
    {
        var items = new List<TeacherDirectoryEntry>();
        await using var connection = await OpenConnectionAsync(cancellationToken);
        await using var command = connection.CreateCommand();
        command.CommandText = @"
            SELECT u.id, u.display_name, u.username, u.email, COUNT(f.id)
            FROM user_accounts u LEFT JOIN fingerprint_templates f ON f.user_account_id = u.id
            WHERE u.role = 'Teacher' AND u.is_active = TRUE
            GROUP BY u.id, u.display_name, u.username, u.email ORDER BY u.display_name;";
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            items.Add(new TeacherDirectoryEntry(reader.GetInt64(0), reader.GetString(1), reader.GetString(2), reader.GetString(3), reader.GetInt32(4)));
        }
        return items;
    }

    public async Task<OperationResult> DeleteTeacherAsync(long accountId, CancellationToken cancellationToken = default)
    {
        await using var connection = await OpenConnectionAsync(cancellationToken);

        await using (var scheduled = connection.CreateCommand())
        {
            scheduled.CommandText = @"
                SELECT EXISTS(
                    SELECT 1 FROM class_schedules
                    WHERE teacher_account_id = @id AND schedule_date >= CURRENT_DATE
                );";
            scheduled.Parameters.AddWithValue("@id", NpgsqlDbType.Bigint, accountId);
            if ((bool)(await scheduled.ExecuteScalarAsync(cancellationToken) ?? false))
            {
                return OperationResult.Failure("Delete or reassign this teacher's current and future schedules before removing the account.");
            }
        }

        await using var command = connection.CreateCommand();
        command.CommandText = @"
            DELETE FROM user_accounts
            WHERE id = @id AND role = 'Teacher';";
        command.Parameters.AddWithValue("@id", NpgsqlDbType.Bigint, accountId);
        return await command.ExecuteNonQueryAsync(cancellationToken) == 1
            ? OperationResult.Success()
            : OperationResult.Failure("The teacher account was not found.");
    }

