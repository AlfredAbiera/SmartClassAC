using Npgsql;
using NpgsqlTypes;
using System.Security.Cryptography;
using System.Text;

namespace SmartClassAC.Services;

/// <summary>
/// Server-side persistence for the Supabase PostgreSQL database. Credentials stay on the server;
/// browser clients never receive a Supabase database password.
/// </summary>
public sealed class SupabasePostgresUserAccountRepository : IUserAccountRepository
{
    private const string ConnectionStringName = "SmartClassSupabase";
    private readonly string _connectionString;

    public SupabasePostgresUserAccountRepository(IConfiguration configuration)
    {
        var configuredConnectionString = configuration.GetConnectionString(ConnectionStringName);
        if (string.IsNullOrWhiteSpace(configuredConnectionString))
        {
            throw new InvalidOperationException(
                "Set ConnectionStrings:SmartClassSupabase with the PostgreSQL connection string from Supabase Connect.");
        }

        NpgsqlConnectionStringBuilder builder;
        try
        {
            builder = new NpgsqlConnectionStringBuilder(configuredConnectionString);
        }
        catch (ArgumentException exception)
        {
            throw new InvalidOperationException("The Supabase PostgreSQL connection string is invalid.", exception);
        }

        if (string.IsNullOrWhiteSpace(builder.Host))
        {
            throw new InvalidOperationException("The Supabase PostgreSQL connection string must include its host.");
        }

        if (builder.SslMode is SslMode.Disable or SslMode.Allow or SslMode.Prefer)
        {
            throw new InvalidOperationException(
                "Supabase requires an encrypted connection. Set SSL Mode=Require or, when a root certificate is configured, SSL Mode=VerifyFull.");
        }

        builder.ApplicationName = "SmartClassAC";
        _connectionString = builder.ConnectionString;
    }

    public async Task InitializeAsync(DefaultAdminOptions defaultAdmin, string passwordHash, CancellationToken cancellationToken)
    {
        await using var connection = await OpenConnectionAsync(cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE TABLE IF NOT EXISTS user_accounts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL,
                display_name VARCHAR(160) NOT NULL,
                email VARCHAR(254),
                phone VARCHAR(40),
                password_hash VARCHAR(512) NOT NULL,
                role VARCHAR(16) NOT NULL CHECK (role IN ('Admin', 'Teacher')),
                is_default_admin BOOLEAN NOT NULL DEFAULT FALSE,
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            );", cancellationToken);
        await ExecuteAsync(connection, "ALTER TABLE user_accounts ADD COLUMN IF NOT EXISTS phone VARCHAR(40);", cancellationToken);
        await ExecuteAsync(connection, @"
            CREATE UNIQUE INDEX IF NOT EXISTS uq_user_accounts_username_ci
            ON user_accounts (LOWER(username));
            CREATE UNIQUE INDEX IF NOT EXISTS uq_user_accounts_email_ci
            ON user_accounts (LOWER(email)) WHERE email IS NOT NULL;
            CREATE UNIQUE INDEX IF NOT EXISTS uq_user_accounts_default_admin
            ON user_accounts (is_default_admin) WHERE is_default_admin;", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE TABLE IF NOT EXISTS classrooms (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 1000),
                target_temperature INTEGER NOT NULL DEFAULT 22 CHECK (target_temperature BETWEEN 16 AND 30),
                current_temperature NUMERIC(4,1),
                ac_status VARCHAR(24) NOT NULL DEFAULT 'Idle',
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE UNIQUE INDEX IF NOT EXISTS uq_classrooms_name_ci ON classrooms (LOWER(name));", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE TABLE IF NOT EXISTS fingerprint_templates (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
                finger_position VARCHAR(32) NOT NULL,
                template_identifier UUID NOT NULL,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT uq_fingerprint_templates_identifier UNIQUE (template_identifier),
                CONSTRAINT uq_fingerprint_templates_user_finger UNIQUE (user_account_id, finger_position)
            );
            CREATE TABLE IF NOT EXISTS password_reset_tokens (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
                token_hash CHAR(64) NOT NULL UNIQUE,
                expires_utc TIMESTAMPTZ NOT NULL,
                used_utc TIMESTAMPTZ,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_account_expiry
            ON password_reset_tokens (user_account_id, expires_utc DESC);", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE TABLE IF NOT EXISTS class_schedules (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                teacher_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
                original_teacher_account_id BIGINT REFERENCES user_accounts(id) ON DELETE CASCADE,
                classroom_id BIGINT REFERENCES classrooms(id) ON DELETE RESTRICT,
                classroom_name VARCHAR(100) NOT NULL,
                subject_name VARCHAR(160) NOT NULL DEFAULT 'Scheduled Class',
                schedule_date DATE NOT NULL,
                start_time TIME NOT NULL,
                end_time TIME NOT NULL,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT ck_class_schedules_time_range CHECK (end_time > start_time)
            );
            ALTER TABLE class_schedules ADD COLUMN IF NOT EXISTS original_teacher_account_id BIGINT REFERENCES user_accounts(id) ON DELETE CASCADE;
            ALTER TABLE class_schedules ADD COLUMN IF NOT EXISTS classroom_id BIGINT REFERENCES classrooms(id) ON DELETE RESTRICT;
            ALTER TABLE class_schedules ADD COLUMN IF NOT EXISTS subject_name VARCHAR(160) NOT NULL DEFAULT 'Scheduled Class';", cancellationToken);

        await ExecuteAsync(connection, @"
            INSERT INTO classrooms (name, capacity, target_temperature, ac_status)
            SELECT DISTINCT classroom_name, 1, 22, 'Idle'
            FROM class_schedules
            WHERE classroom_name IS NOT NULL
            ON CONFLICT DO NOTHING;

            UPDATE class_schedules AS schedule
            SET classroom_id = classroom.id
            FROM classrooms AS classroom
            WHERE schedule.classroom_id IS NULL
              AND LOWER(schedule.classroom_name) = LOWER(classroom.name);

            UPDATE class_schedules
            SET original_teacher_account_id = teacher_account_id
            WHERE original_teacher_account_id IS NULL;", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE INDEX IF NOT EXISTS ix_class_schedules_teacher_date
            ON class_schedules (teacher_account_id, schedule_date, start_time);
            CREATE INDEX IF NOT EXISTS ix_class_schedules_classroom_date
            ON class_schedules (LOWER(classroom_name), schedule_date, start_time);", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE EXTENSION IF NOT EXISTS btree_gist;
            DO $$
            BEGIN
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ex_class_schedules_teacher_overlap') THEN
                    ALTER TABLE class_schedules ADD CONSTRAINT ex_class_schedules_teacher_overlap
                    EXCLUDE USING gist (
                        teacher_account_id WITH =,
                        tsrange(schedule_date + start_time, schedule_date + end_time, '[)') WITH &&
                    );
                END IF;
                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ex_class_schedules_classroom_overlap') THEN
                    ALTER TABLE class_schedules ADD CONSTRAINT ex_class_schedules_classroom_overlap
                    EXCLUDE USING gist (
                        LOWER(classroom_name) WITH =,
                        tsrange(schedule_date + start_time, schedule_date + end_time, '[)') WITH &&
                    );
                END IF;
            END;
            $$;", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE TABLE IF NOT EXISTS attendance_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                class_schedule_id BIGINT UNIQUE REFERENCES class_schedules(id) ON DELETE SET NULL,
                teacher_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
                classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE RESTRICT,
                time_in_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                time_out_utc TIMESTAMPTZ,
                verification_method VARCHAR(40) NOT NULL DEFAULT 'Biometric',
                status VARCHAR(24) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Completed'))
            );
            CREATE INDEX IF NOT EXISTS ix_attendance_logs_teacher_time ON attendance_logs (teacher_account_id, time_in_utc DESC);
            CREATE UNIQUE INDEX IF NOT EXISTS uq_attendance_logs_one_active_teacher
            ON attendance_logs (teacher_account_id) WHERE time_out_utc IS NULL;

            CREATE TABLE IF NOT EXISTS teacher_requests (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                teacher_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
                request_type VARCHAR(16) NOT NULL CHECK (request_type IN ('Leave', 'EarlyOut', 'Overtime')),
                request_date DATE NOT NULL,
                reason VARCHAR(1000) NOT NULL,
                needs_substitute BOOLEAN NOT NULL DEFAULT FALSE,
                substitute_teacher_account_id BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
                status VARCHAR(16) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
                admin_response VARCHAR(1000),
                reviewed_by_account_id BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                reviewed_utc TIMESTAMPTZ
            );
            CREATE INDEX IF NOT EXISTS ix_teacher_requests_status ON teacher_requests (status, created_utc DESC);
            CREATE UNIQUE INDEX IF NOT EXISTS uq_teacher_requests_pending_day
            ON teacher_requests (teacher_account_id, request_type, request_date)
            WHERE status = 'Pending';

            CREATE TABLE IF NOT EXISTS support_tickets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                teacher_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
                category VARCHAR(100) NOT NULL,
                details VARCHAR(2000) NOT NULL,
                status VARCHAR(16) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Resolved', 'Dismissed')),
                admin_response VARCHAR(2000),
                reviewed_by_account_id BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
                created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                resolved_utc TIMESTAMPTZ
            );
            CREATE INDEX IF NOT EXISTS ix_support_tickets_status ON support_tickets (status, created_utc DESC);

            CREATE TABLE IF NOT EXISTS temperature_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                classroom_id BIGINT NOT NULL REFERENCES classrooms(id) ON DELETE CASCADE,
                actor_account_id BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
                measured_temperature NUMERIC(4,1),
                target_temperature INTEGER CHECK (target_temperature BETWEEN 16 AND 30),
                event_type VARCHAR(32) NOT NULL,
                notes VARCHAR(1000),
                recorded_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS ix_temperature_logs_classroom_time ON temperature_logs (classroom_id, recorded_utc DESC);", cancellationToken);

        await ExecuteAsync(connection, @"
            CREATE OR REPLACE FUNCTION public.smartclass_set_updated_utc()
            RETURNS TRIGGER LANGUAGE plpgsql AS $$
            BEGIN
                NEW.updated_utc = CURRENT_TIMESTAMP;
                RETURN NEW;
            END;
            $$;
            DROP TRIGGER IF EXISTS trg_user_accounts_set_updated_utc ON user_accounts;
            CREATE TRIGGER trg_user_accounts_set_updated_utc BEFORE UPDATE ON user_accounts
            FOR EACH ROW EXECUTE FUNCTION public.smartclass_set_updated_utc();
            DROP TRIGGER IF EXISTS trg_classrooms_set_updated_utc ON classrooms;
            CREATE TRIGGER trg_classrooms_set_updated_utc BEFORE UPDATE ON classrooms
            FOR EACH ROW EXECUTE FUNCTION public.smartclass_set_updated_utc();
            DROP TRIGGER IF EXISTS trg_class_schedules_set_updated_utc ON class_schedules;
            CREATE TRIGGER trg_class_schedules_set_updated_utc BEFORE UPDATE ON class_schedules
            FOR EACH ROW EXECUTE FUNCTION public.smartclass_set_updated_utc();", cancellationToken);

        await ExecuteAsync(connection, @"
            ALTER TABLE user_accounts ENABLE ROW LEVEL SECURITY;
            ALTER TABLE classrooms ENABLE ROW LEVEL SECURITY;
            ALTER TABLE fingerprint_templates ENABLE ROW LEVEL SECURITY;
            ALTER TABLE password_reset_tokens ENABLE ROW LEVEL SECURITY;
            ALTER TABLE class_schedules ENABLE ROW LEVEL SECURITY;
            ALTER TABLE attendance_logs ENABLE ROW LEVEL SECURITY;
            ALTER TABLE teacher_requests ENABLE ROW LEVEL SECURITY;
            ALTER TABLE support_tickets ENABLE ROW LEVEL SECURITY;
            ALTER TABLE temperature_logs ENABLE ROW LEVEL SECURITY;", cancellationToken);

        await SeedDefaultAdminAsync(connection, defaultAdmin, passwordHash, cancellationToken);
    }

