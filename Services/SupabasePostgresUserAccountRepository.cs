    private static async Task SeedDefaultAdminAsync(NpgsqlConnection connection, DefaultAdminOptions admin, string passwordHash, CancellationToken cancellationToken, NpgsqlTransaction? transaction = null)
    {
        await using var seed = connection.CreateCommand();
        seed.Transaction = transaction;
        seed.CommandText = @"
            INSERT INTO user_accounts (username, display_name, password_hash, role, is_default_admin)
            SELECT @username, 'System Administrator', @passwordHash, 'Admin', TRUE
            WHERE NOT EXISTS (SELECT 1 FROM user_accounts WHERE role = 'Admin')
            ON CONFLICT DO NOTHING;";
        seed.Parameters.AddWithValue("@username", NpgsqlDbType.Varchar, admin.Username.Trim());
        seed.Parameters.AddWithValue("@passwordHash", NpgsqlDbType.Varchar, passwordHash);
        await seed.ExecuteNonQueryAsync(cancellationToken);
    }

