                await insert.ExecuteNonQueryAsync(cancellationToken);
            }

            await transaction.CommitAsync(cancellationToken);
            return new PasswordResetDelivery(recipient, rawToken);
        }
        catch
        {
            await transaction.RollbackAsync(cancellationToken);
            throw;
        }
